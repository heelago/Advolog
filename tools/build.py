def zip_dir(destination: Path, members: list[tuple[str, bytes]]) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        destination.unlink()
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for arcname, data in members:
            info = zipfile.ZipInfo(arcname)
            info.date_time = (2026, 11, 11, 0, 0, 0)
            info.compress_type = zipfile.ZIP_DEFLATED
            # Stable external attributes, so a rebuild is byte-stable.
            info.external_attr = 0o644 << 16
            zf.writestr(info, data)


def package_zip_members() -> list[tuple[str, bytes]]:
    members = []
    for path in sorted(PKG.rglob("*")):
        if not path.is_file():
            continue
        if path.name == ".DS_Store" or "__pycache__" in path.parts:
            continue
        rel = path.relative_to(PKG).as_posix()
        members.append((f"package/{rel}", path.read_bytes()))
    return members


def skill_zip_members() -> list[tuple[str, bytes]]:
    """Twelve skill folders, each with shared references copied in."""
    members = []
    ref_blobs = {
        name: reference_text(name).encode("utf-8") for name in REFERENCES
    }
    for skill in SKILL_ORDER:
        members.append(
            (f"{skill}/SKILL.md", skill_text(skill).encode("utf-8"))
        )
        for name, blob in ref_blobs.items():
            members.append((f"{skill}/references/{name}", blob))
    return members


def one_skill_zip_members() -> list[tuple[str, bytes]]:
    members = [("advolog/SKILL.md", router_skill().encode("utf-8"))]
    for name in SKILL_ORDER:
        members.append(
            (f"advolog/references/{name}.md", skill_text(name).encode("utf-8"))
        )
    for name in REFERENCES:
        members.append(
            (f"advolog/references/{name}", reference_text(name).encode("utf-8"))
        )
    return members


def write_outputs(outputs: dict[str, str]) -> None:
    for rel, text in outputs.items():
        write(ROOT / rel, text)


def build_zips() -> None:
    zip_dir(DOCS / "advolog.zip", package_zip_members())
    zip_dir(DOCS / "advolog-skills.zip", skill_zip_members())
    zip_dir(DOCS / "advolog-skill.zip", one_skill_zip_members())


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    outputs = planned_outputs()
    write_outputs(outputs)
    refresh_marked_files()
    # Fact blocks and embeds may sit in generated files only after the first write.
    # Re-apply in case a generated file contains markers (it should not).
    build_zips()
    print(f"wrote {len(outputs)} files")
    print(f"zip package {sha256(DOCS / 'advolog.zip')[:12]}")
    print(f"zip skills  {sha256(DOCS / 'advolog-skills.zip')[:12]}")
    print(f"zip skill   {sha256(DOCS / 'advolog-skill.zip')[:12]}")


if __name__ == "__main__":
    main()
