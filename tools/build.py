GENERATED_BANNER = (
    "<!-- GENERATED by tools/build.py. Do not edit by hand. Source: package/core.md, "
    "package/skills/, package/references/, package/prompts/. -->\n"
)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def skill_text(name: str) -> str:
    return read(PKG / "skills" / name / "SKILL.md").rstrip() + "\n"


def reference_text(name: str) -> str:
    return read(PKG / "references" / name).rstrip() + "\n"


def prompt_text(name: str) -> str:
    return read(PKG / "prompts" / name).rstrip() + "\n"


def fence(title: str, body: str) -> str:
    return f"\n\n# {title}\n\n{body}"


def modules_document(title: str, names: list[str], include_references: bool) -> str:
    parts = [
        GENERATED_BANNER,
        f"# {title}\n",
        "Read the project instructions (the Advolog constitution) first. "
        "They win on any conflict with this file. Act as Advolog only when those "
        "instructions are present. If a section you need is not in this file, "
        "read it from another Advolog file in the project before you write.\n",
    ]
    for name in names:
        parts.append(fence(f"Skill: {name}", skill_text(name)))
    if include_references:
        for name in REFERENCES:
            parts.append(fence(f"Reference: {name}", reference_text(name)))
    return "".join(parts).rstrip() + "\n"


def bundle_document() -> str:
    parts = [
        GENERATED_BANNER,
        "# Advolog, single-file fallback\n",
        "Use this file only when the project cannot hold the instructions field "
        "plus the separate module files. The constitution is the first section "
        "and wins on any conflict. Prefer the instructions-field layout when the "
        "field accepts it.\n",
        fence("Constitution", read(PKG / "core.md").rstrip() + "\n"),
    ]
    for name in SKILL_ORDER:
        parts.append(fence(f"Skill: {name}", skill_text(name)))
    for name in REFERENCES:
        parts.append(fence(f"Reference: {name}", reference_text(name)))
    for name in PROMPTS:
        parts.append(fence(f"Prompt: {name}", prompt_text(name)))
    return "".join(parts).rstrip() + "\n"


def instructions_document() -> str:
    # Exact copy of the constitution. A generated banner would push the paste
    # over the proposed 7,000-character Instructions cap (pending live test T1).
    return read(PKG / "core.md")


def planned_outputs() -> dict[str, str]:
    """Relative path (from repo root, posix) -> file text."""
    out: dict[str, str] = {}
    out["package/web/instructions.md"] = instructions_document()
    out["package/web/advolog-modules.md"] = modules_document(
        "Advolog modules", SKILL_ORDER, include_references=True
    )
    for filename, title, names in GROUPS:
        out[f"package/web/{filename}"] = modules_document(
            title, names, include_references=True
        )
    bundle = bundle_document()
    out["package/advolog-chatgpt-bundle.md"] = bundle
    for rel, text in list(out.items()):
        name = Path(rel).name
        if rel.startswith("package/web/") or rel.endswith("advolog-chatgpt-bundle.md"):
            out[f"docs/download/{name}"] = text
    return out


def apply_fact_blocks(text: str) -> str:
    for name, body in FACT_BLOCKS.items():
        start = f"<!-- facts:{name} -->"
        end = f"<!-- /facts:{name} -->"
        if start not in text or end not in text:
            continue
        pre, rest = text.split(start, 1)
        _, post = rest.split(end, 1)
        text = pre + start + "\n" + body + "\n" + end + post
    return text


def fenced_block(markdown: str, which: int) -> str:
    """Return the Nth fenced code block (0-based), without the fences."""
    parts = markdown.split("```")
    # parts[1], parts[3], ... are code
    codes = [parts[i] for i in range(1, len(parts), 2)]
    if which >= len(codes):
        raise SystemExit(f"starter prompt is missing fenced block {which}")
    code = codes[which]
    if code.startswith("\n"):
        code = code[1:]
    return code.rstrip("\n")


def html_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def apply_embeds(text: str) -> str:
    starter = read(PKG / "starter" / "starter-prompt.md")
    he = html_escape(fenced_block(starter, 0))
    en = html_escape(fenced_block(starter, 1))
    core = html_escape(read(PKG / "core.md").rstrip() + "\n")
    replacements = {
        "starter-he": he,
        "starter-en": en,
        "instructions": core,
    }
    for name, body in replacements.items():
        start = f"<!-- embed:{name} -->"
        end = f"<!-- /embed:{name} -->"
        if start not in text or end not in text:
            continue
        pre, rest = text.split(start, 1)
        _, post = rest.split(end, 1)
        text = pre + start + "\n" + body + "\n" + end + post
    return text


def refresh_marked_files() -> list[Path]:
    touched = []
    candidates = list((PKG / "setup").glob("*.md")) + list(DOCS.glob("*.html"))
    for path in candidates:
        original = read(path)
        updated = apply_embeds(apply_fact_blocks(original))
        if updated != original:
            write(path, updated)
            touched.append(path)
    return touched


